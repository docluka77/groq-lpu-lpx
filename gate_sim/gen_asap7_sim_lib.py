def get_used_cells():
    used = set()
    cell_re = re.compile(r'^\s*([A-Za-z0-9_]+_ASAP7_[A-Za-z0-9_]+)\s+')
    for vfile in sorted(glob.glob(os.path.join(SYNTH_DIR, '*_asap7_netlist.v'))):
        with open(vfile, 'r') as f:
            for line in f:
                m = cell_re.match(line)
                if m:
                    used.add(m.group(1))
    return sorted(used)

def liberty_expr_to_verilog(expr):
    s = expr.strip().strip('"')
    s = s.replace('!', '~')
    s = s.replace('*', ' & ')
    s = s.replace('+', ' | ')
    return s

def parse_liberty_cells(lib_path, target_cells):
    with open(lib_path, 'r') as f:
        text = f.read()

    cells_data = {}
    for cname in target_cells:
        marker = f'cell ({cname}) {{'
        idx = text.find(marker)
        if idx == -1:
            raise RuntimeError(f'Cell {cname} not found in {lib_path}')
        depth = 0
        end_idx = idx
        for i in range(idx, len(text)):
            if text[i] == '{':
                depth += 1
            elif text[i] == '}':
                depth -= 1
                if depth == 0:
                    end_idx = i + 1
                    break
        block = text[idx:end_idx]

        ff_info = None
        ff_m = re.search(r'ff\s*\(\s*(\w+)\s*,\s*(\w+)\s*\)\s*\{([^}]*)\}', block)
        if ff_m:
            q_var, qn_var, ff_body = ff_m.group(1), ff_m.group(2), ff_m.group(3)
            clk_m = re.search(r'clocked_on\s*:\s*"([^"]+)"', ff_body)
            next_m = re.search(r'next_state\s*:\s*"([^"]+)"', ff_body)
            clr_m = re.search(r'clear\s*:\s*"([^"]+)"', ff_body)
            pre_m = re.search(r'preset\s*:\s*"([^"]+)"', ff_body)
            ff_info = {
                'q_var': q_var,
                'qn_var': qn_var,
                'clocked_on': clk_m.group(1) if clk_m else 'CLK',
                'next_state': next_m.group(1) if next_m else 'D',
                'clear': clr_m.group(1) if clr_m else None,
                'preset': pre_m.group(1) if pre_m else None,
            }

        pins = []
        for pm in re.finditer(r'\bpin\s*\(\s*(\w+)\s*\)\s*\{', block):
            pname = pm.group(1)
            pstart = pm.start()
            pdepth = 0
            pend = pstart
            for i in range(pstart, len(block)):
                if block[i] == '{':
                    pdepth += 1
                elif block[i] == '}':
                    pdepth -= 1
                    if pdepth == 0:
                        pend = i + 1
                        break
            pbody = block[pstart:pend]
            dir_m = re.search(r'direction\s*:\s*(\w+)\s*;', pbody)
            func_m = re.search(r'function\s*:\s*"([^"]+)"\s*;', pbody)
            pins.append({
                'name': pname,
                'direction': dir_m.group(1) if dir_m else 'input',
                'function': func_m.group(1) if func_m else None
            })
        cells_data[cname] = {'pins': pins, 'ff': ff_info}
    return cells_data

def generate_verilog(cells_data, out_path):
    lines = [
        '// Auto-generated by gate_sim/gen_asap7_sim_lib.py from asap7_rvt_ff.lib',
        '// 100% functional Verilator-compatible ASAP7 7nm standard-cell behavioral primitives',
        '/* verilator lint_off DECLFILENAME */',
        '/* verilator lint_off UNUSEDSIGNAL */',
        '`timescale 1ns/1ps',
        ''
    ]
    for cname, info in sorted(cells_data.items()):
        pins = info['pins']
        ff = info['ff']
        port_names = [p['name'] for p in pins]
        lines.append(f'module {cname} ({", ".join(port_names)});')
        for p in pins:
            lines.append(f'  {p["direction"]} wire {p["name"]};')

        if ff is None:
            for p in pins:
                if p['direction'] == 'output' and p['function']:
                    vexpr = liberty_expr_to_verilog(p['function'])
                    lines.append(f'  assign {p["name"]} = {vexpr};')
        else:
            q_var = ff['q_var']
            qn_var = ff['qn_var']
            clk = ff['clocked_on'].strip()
            nxt = liberty_expr_to_verilog(ff['next_state'])
            clr = ff['clear']
            pre = ff['preset']
            lines.append(f'  reg {q_var}_r;')
            sens = [f'posedge {clk}']
            if clr:
                clr_sig = clr.replace('!', '').strip()
                edge = 'negedge' if '!' in clr else 'posedge'
                sens.append(f'{edge} {clr_sig}')
            if pre:
                pre_sig = pre.replace('!', '').strip()
                edge = 'negedge' if '!' in pre else 'posedge'
                sens.append(f'{edge} {pre_sig}')
            lines.append(f'  always @({" or ".join(sens)}) begin')
            if clr and pre:
                clr_cond = liberty_expr_to_verilog(clr)
                pre_cond = liberty_expr_to_verilog(pre)
                # Note: when RESETN=0 (preset of IQN) vs SETN=0 (clear of IQN)
                lines.append(f'    if ({pre_cond}) {q_var}_r <= 1\'b1;')
                lines.append(f'    else if ({clr_cond}) {q_var}_r <= 1\'b0;')
                lines.append(f'    else {q_var}_r <= ({nxt});')
            elif clr:
                clr_cond = liberty_expr_to_verilog(clr)
                lines.append(f'    if ({clr_cond}) {q_var}_r <= 1\'b0;')
                lines.append(f'    else {q_var}_r <= ({nxt});')
            elif pre:
                pre_cond = liberty_expr_to_verilog(pre)
                lines.append(f'    if ({pre_cond}) {q_var}_r <= 1\'b1;')
                lines.append(f'    else {q_var}_r <= ({nxt});')
            else:
                lines.append(f'    {q_var}_r <= ({nxt});')
            lines.append('  end')
            for p in pins:
                if p['direction'] == 'output' and p['function']:
                    fn = p['function'].strip()
                    if fn == q_var:
                        lines.append(f'  assign {p["name"]} = {q_var}_r;')
                    elif fn == qn_var:
                        lines.append(f'  assign {p["name"]} = ~{q_var}_r;')
                    else:
                        vexpr = liberty_expr_to_verilog(fn)
                        lines.append(f'  assign {p["name"]} = {vexpr};')
        lines.append('endmodule\n')

    lines.append('/* verilator lint_on UNUSEDSIGNAL */')
    lines.append('/* verilator lint_on DECLFILENAME */')
    with open(out_path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'[Stage 17] Generated {len(cells_data)} ASAP7 standard-cell behavioral primitives in {out_path}')

